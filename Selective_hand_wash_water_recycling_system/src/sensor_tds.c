/*
 * sensor_tds.c —— 模拟 TDS（电导率）传感器驱动实现
 * ---------------------------------------------------------------------------
 *  本文件解决什么问题
 *  ---------------------------------------------------------------------------
 *  模拟 TDS 模块输出一路与"水中离子浓度"相关的直流电压，是本项目区分
 *  清水 / 含皂液水的主判据传感器。它有两个必须处理的问题：
 *    ① 读数随水温变化（电解质电导率约 +2 %/℃，实验 2 报告 2.3 节），
 *       不补偿就无法跨时段、跨水温比较；
 *    ② 输出接近量程上限时响应被压缩，接线错误时读数会贴到电源轨。
 *  本驱动把一次 ADC 码统一换算成：
 *      mV → 补偿到 25 ℃ 的 mV25 → DFRobot 经验多项式的参考 ppm，
 *  同时给出 rail（贴轨）/ saturated（超量程）两个"数据可信度"标记。
 *  判别层只使用相对量（ΔEC / g），ppm 字段仅供过程参考和日志。
 *
 *  接线（断电接线，接好再上电）
 *  ---------------------------------------------------------------------------
 *  TDS 模块 VCC  -> U1-12（3.3V，U1 从上往下第 9 孔）
 *  TDS 模块 GND  -> U1-16（GND）
 *  TDS 模块 AOUT -> U1-6 = P014 / AN12（0~2.3 V 直连安全；模拟绝对最大 3.6 V）
 *  TDS 探针      -> 模块 2 针密封座（插紧、别进水、别碰杯壁/杯底）
 *  模块必须 3.3 V 供电：若接 5 V 又插着 DS18B20，DQ 会被上拉到 5 V，超 MCU 耐压。
 *
 *  原理与公式（来源：实验 2 报告 2.2~2.4 节 + DFRobot 产品资料）
 *  ---------------------------------------------------------------------------
 *  ① ADC → 电压：mV = raw × VREF / 4095
 *     （12 位右对齐、VREF = 板载 3.3 V = 3300 mV，四舍五入到 1 mV）
 *  ② 温度补偿：V25 = V / (1 + 0.02 × (T − 25))
 *     T 为水侧水温（来自 DS18B20 / 手输 / 兜底），限幅 [-5, 60] ℃；
 *     补偿系数再取 0.2 下限，防止异常温度把电压放大到离谱。
 *  ③ 参考 TDS（DFRobot 经验多项式，V 为 25 ℃ 电压，单位 V）：
 *        ppm = (133.42V³ − 255.86V² + 857.39V) × 0.5 × K
 *     K = cal_k，默认 1.0；只有拿到 1413 µS/cm 标准液才值得单点标定。
 *
 *  参数（默认值来源 + 怎么标定）
 *  ---------------------------------------------------------------------------
 *  - TDS_RAIL_ADC = 4000（≈3.22 V）：几乎必然接错线/过压 → 判 RANGE；
 *    若现场实测稳定在 3.0~3.2 V 之间，多半是模块批次差异，不是 rail。
 *  - TDS_SAT_MV = 2400：超过模块标称 2.3 V；只置"可能饱和"标志，不当故障。
 *    来源：实验 2 高浓度肥皂水段 2356 mV 已越过标称上限（响应可能被压缩）。
 *  - TDS_ALPHA_PER_C = 0.02、TDS_TEMP_REF_C = 25.0：电解液经验参数；
 *    若有标准液和恒温条件，可用两点法（如 20 ℃ / 30 ℃）复标。
 *  - cal_k：没有标准液时保持 1.0，不要凭感觉调。
 *
 *  注意事项（实验 2 真实踩坑）
 *  ---------------------------------------------------------------------------
 *  1) 参考 ppm 不可当绝对值：没有标准液、模块接近量程上限，报告口径只写
 *     mV / 相对变化 / σ 倍数，禁止写"TDS = xxx ppm 达标"。
 *  2) 探头在空气里是开路伪值（约 1.6 V），不是 0 ppm —— 基线必须在水样里采。
 *  3) AOUT 接触不良时读数会卡在固定高值、插水也不变：每次实验前用
 *     "插水看读数是否变化"做接线自检。
 *  4) 温补用错温度会成倍放大误差（实验 2：假 0.00 ℃ 让 mV25 翻倍），
 *     所以本驱动对温度做 NaN / 越界清洗，温度来源不明时由上层标 FIX。
 * ---------------------------------------------------------------------------
 */

#include <stddef.h>      /* NULL */
#include "sensor_tds.h"

/* 模块内部配置副本（单实例模块，按接口契约用文件内 static 保存）。
 * 初值 cal_k = 1.0：即使调用者忘记 tds_init()，换算也是"未标定"的合理默认。 */
static tds_cfg_t s_cfg = { 1.0f };

/**
 * @brief 初始化 TDS 驱动（保存配置）
 *
 * 作用：把标定系数拷贝进模块内部，供后续 tds_convert / tds_ppm_from_mv25 使用。
 * 参数：p_cfg —— 配置指针；NULL 表示全部用默认值（cal_k = 1.0）。
 * 返回：无。
 * 时序：纯赋值，不访问硬件、不阻塞；可在 app_main 初始化阶段反复调用。
 * 注意：① cal_k 只接受 (0, 10] 的正数：0 会让 ppm 恒为 0（看起来像纯净水，
 *          对安全侧判据是危险的方向）；负数/NaN 无物理意义，一律回落 1.0。
 *       ② 本驱动不直接操作 ADC；ADC 的打开/扫描由 sensor_pipeline 负责。
 */
void tds_init(const tds_cfg_t *p_cfg)
{
    float k = 1.0f;   /* 默认：无标准液，不标定 */

    if (NULL != p_cfg)
    {
        if ((p_cfg->cal_k > 0.0f) && (p_cfg->cal_k <= 10.0f))
        {
            k = p_cfg->cal_k;
        }
    }

    s_cfg.cal_k = k;
}

/**
 * @brief 核心转换：ADC 码 + 水温 → 电压 / 温补电压 / 参考 ppm / 可信度标记
 *
 * 作用：一次完成 ADC→mV、rail/saturated 判定、温度清洗、温补、参考 ppm 换算。
 * 参数：raw_adc      —— 中值后的 ADC 码（12 位）；
 *       water_temp_c —— 当前水温（℃，可以来自 DS18B20 / 手输 / 兜底）；
 *       p_out        —— 输出结构体（必须非 NULL）。
 * 返回：SENSOR_OK            换算完成，数据可用；
 *       SENSOR_ERR_PARAM     p_out 为空；
 *       SENSOR_ERR_RANGE     ADC 贴轨（rail），读数不可信，上层应判传感器故障。
 *       （saturated 不改变返回码，只在 p_out->saturated 里提示响应可能压缩。）
 * 时序：纯计算，微秒级；每 50 ms tick 调用一次。
 * 注意：① p_out 的所有字段都会写满，即使返回 RANGE 也保留原始换算值，
 *          方便上层打印"坏在哪"（如 CSV 的 note=TDS_RAIL）；
 *       ② 温度非法（NaN/超出 [-5,60]）会被清洗到参考温度/边界，
 *          但**不会**把状态置为错误——温度来源的可信度由上层（pipeline）负责
 *          标记 water_temp_from_sensor=false，本驱动只管数值安全。
 */
sensor_status_t tds_convert(uint16_t raw_adc, float water_temp_c, tds_reading_t *p_out)
{
    if (NULL == p_out)
    {
        return SENSOR_ERR_PARAM;
    }

    /* ---- 1) ADC 码 → 毫伏 ---- */
    uint32_t mv = sensor_adc_to_mv(raw_adc, TDS_ADC_FULL_SCALE, TDS_VREF_MV_DEFAULT);
    p_out->raw_adc = raw_adc;
    p_out->mv      = mv;

    /* ---- 2) 可信度标记（只标记，不改变原始读数） ----
     * rail：ADC 快贴到 3.3 V 电源轨。TDS 模块正常输出最大约 2.3 V，
     *       出现 ≥4000 几乎只有两种原因：AOUT 接错到 3.3 V/GND 之外的脚、
     *       或模块内部损坏。必须让上层按"传感器故障 → 排空"处理。
     * saturated：超过模块标称 0~2.3 V 上限，读数仍然可比较，但斜率可能被压缩，
     *       所以只提示，不当故障（真实洗手水浓度低，通常不会进入该区）。 */
    p_out->rail      = (raw_adc >= TDS_RAIL_ADC);
    p_out->saturated = (mv > TDS_SAT_MV);

    /* ---- 3) 水温清洗（NaN / 越界 → 参考温度或边界） ----
     * 温补公式对温度敏感：温度错 10 ℃ → 电压差约 20%，会直接改变判别结论。
     * NaN 单独判（按 IEEE-754 位型检查，见 sensor_common.h 的 sensor_is_nan_f32），
     * 其余超范围值用统一限幅器压到 [-5, 60] ℃。 */
    float temp_c = water_temp_c;
    if (sensor_is_nan_f32(temp_c))
    {
        temp_c = TDS_TEMP_REF_C;   /* NaN：当成 25 ℃（此时温补≈恒等，不放大误差） */
    }
    temp_c = sensor_clampf(temp_c, TDS_TEMP_MIN_C, TDS_TEMP_MAX_C);

    /* ---- 4) 温度补偿：V25 = V / (1 + α(T − 25)) ----
     * 电解质溶液电导率随温度近似线性上升（约 2 %/℃，实验 2 报告 2.3 节）：
     * 水温高 → 同样离子浓度下电压更高，所以要把高温读数"压回" 25 ℃ 口径。
     * 系数下限 0.2（TDS_COEFF_MIN）：即使温度参数被改坏，放大倍数最多 5 倍，
     * 不会出现"除以 0.01"这种离谱值。上限 4.0 只是防御（本工程温度已被限幅，
     * 实际系数最大约 1.7）。 */
    float coeff = 1.0f + (TDS_ALPHA_PER_C * (temp_c - TDS_TEMP_REF_C));
    coeff = sensor_clampf(coeff, TDS_COEFF_MIN, 4.0f);

    p_out->mv25 = ((float) mv) / coeff;
    if (!(p_out->mv25 > 0.0f))
    {
        p_out->mv25 = 0.0f;   /* 理论不会发生（mv≥0、coeff>0），防御 NaN */
    }

    /* ---- 5) 25 ℃ 电压 → 参考 ppm ---- */
    p_out->ppm25 = tds_ppm_from_mv25(p_out->mv25);

    /* ---- 6) 状态：贴轨才是硬错误；饱和/温补完好的数据都算 OK ---- */
    if (p_out->rail)
    {
        p_out->status = SENSOR_ERR_RANGE;
        return p_out->status;
    }

    p_out->status = SENSOR_OK;
    return SENSOR_OK;
}

/**
 * @brief 只做 25 ℃ 电压 → 参考 ppm（供标定/复算用）
 *
 * 作用：把 mV25 代入 DFRobot 经验多项式，得到参考 TDS；内部包含 cal_k 与限幅。
 * 参数：mv25 —— 温度补偿到 25 ℃ 的电压（mV）。
 * 返回：参考 ppm（0~TDS_PPM_LIMIT；非法输入返回 0）。
 * 时序：纯计算，几次乘加。
 * 注意：① 该多项式只对特定模块、特定量程成立；没有标准液时它只是
 *          "过程参考"，不能当绝对浓度，更不能作为达标依据；
 *       ② 输入 ≤0 或 NaN 直接返回 0（负电压在物理上无意义）；
 *       ③ 限幅 0~2000 只是防止日志/CSV 出现离谱数值，不代表量程能力。
 */
float tds_ppm_from_mv25(float mv25)
{
    if (!(mv25 > 0.0f))
    {
        return 0.0f;
    }

    /* 多项式以 V 为单位：v = mV / 1000 */
    float v = mv25 / 1000.0f;

    /* DFRobot 经验多项式（Horner 形式，少两次乘法）：
     *   ppm = (133.42·v³ − 255.86·v² + 857.39·v) × 0.5 × K
     *       = ((133.42·v − 255.86)·v + 857.39)·v × 0.5 × K
     * 公式只对 0~2.3 V 标称区间有效，超出后仅作趋势参考。 */
    float ppm = (((133.42f * v) - 255.86f) * v + 857.39f) * v;

    /* ×0.5（EC→TDS 经验系数，实际 0.5~0.7 随水样组成变化）× 标定系数 */
    ppm *= (0.5f * s_cfg.cal_k);

    if (!(ppm > 0.0f))
    {
        ppm = 0.0f;   /* 低电压端多项式可能算出负值/NaN，按 0 处理 */
    }
    if (ppm > TDS_PPM_LIMIT)
    {
        ppm = TDS_PPM_LIMIT;   /* 只防打印异常，不表示量程上限 */
    }

    return ppm;
}
